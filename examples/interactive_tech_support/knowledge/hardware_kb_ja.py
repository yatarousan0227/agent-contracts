def search_hardware_kb_ja(query: str) -> dict[str, Any] | None:
    """ハードウェアナレッジベースから関連する問題を検索します。

    Args:
        query: ユーザーのクエリ文字列。

    Returns:
        最も関連性の高い問題データ、または一致するものがない場合はNone。
    """
    query_lower = query.lower()

    # すべてのカテゴリを検索
    for category, data in HARDWARE_KB_JA.items():
        keywords = data.get("keywords", [])

        # キーワードが一致するか確認
        for keyword in keywords:
            if keyword.lower() in query_lower:
                # 最初の関連する問題を返す
                issues = data.get("issues", {})
                if issues:
                    # クエリに基づいて特定の問題を見つけようとする
                    for issue_key, issue_data in issues.items():
                        issue_title = issue_data.get("title", "").lower()
                        if any(word in query_lower for word in issue_title.split()):
                            return {
                                "category": category,
                                "issue": issue_key,
                                **issue_data,
                            }

                    # デフォルトとして最初の問題を返す
                    first_issue = next(iter(issues.items()))
                    return {
                        "category": category,
                        "issue": first_issue[0],
                        **first_issue[1],
                    }

    return None
